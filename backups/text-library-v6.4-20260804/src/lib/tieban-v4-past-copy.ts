function axisAddress(fact: AtomicFact) {
  const match = /^fact\.v4\.axis\.([^.]+)\.(.+)$/u.exec(fact.id);
  return match ? { group: match[1], option: match[2] } : null;
}

export function hasCuratedPastLifeCopyV4(fact: AtomicFact) {
  const axis = axisAddress(fact);
  if (axis) return Boolean(AXIS_PAST_COPY[axis.group]?.[axis.option]);
  return Boolean(LEGACY_PAST_COPY[fact.semanticFamily ?? ""]);
}

export function pastLifeCopyV4(fact: AtomicFact): PastLifeCopyV4 {
  const axis = axisAddress(fact);
  if (axis) return AXIS_PAST_COPY[axis.group]?.[axis.option] ?? FALLBACK_PAST_COPY[fact.domain];
  return LEGACY_PAST_COPY[fact.semanticFamily ?? ""] ?? FALLBACK_PAST_COPY[fact.domain];
}

